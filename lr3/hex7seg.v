// собственный модуль: дешифратор для семисегментного индикатора
// вход - одна цифра (4 бита), выход - сегменты HEX[6:0]
// на плате DE2-115 сегмент горит, когда на него подан 0
//   bcd = 0..9 -> цифра, 4'hA -> знак "-", 4'hF -> индикатор погашен
module hex7seg
(
  input  [3:0] bcd,
  output reg [6:0] seg      // seg[0]=a, seg[1]=b, ... seg[6]=g
);

always @(*)
  case (bcd)
    4'd0: seg = 7'b1000000;
    4'd1: seg = 7'b1111001;
    4'd2: seg = 7'b0100100;
    4'd3: seg = 7'b0110000;
    4'd4: seg = 7'b0011001;
    4'd5: seg = 7'b0010010;
    4'd6: seg = 7'b0000010;
    4'd7: seg = 7'b1111000;
    4'd8: seg = 7'b0000000;
    4'd9: seg = 7'b0010000;
    4'hA: seg = 7'b0111111;   // "-"
    default: seg = 7'b1111111; // все сегменты погашены
  endcase

endmodule
