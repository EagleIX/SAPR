// ЛР3, часть 2: система регулирования движением на перекрестке (плата DE1)
// вариант 3: главная дорога (2 полосы), второстепенная дорога (1 полоса)
//
// главная дорога: два светофора (север и юг), показывают одно и то же
//   север: красный LEDR0, желтый LEDR1, зеленый LEDG0
//   юг:    красный LEDR2, желтый LEDR3, зеленый LEDG1
// второстепенная дорога: одна полоса, один светофор
//   запад: красный LEDR4, желтый LEDR5, зеленый LEDG2
// (желтых светодиодов на плате нет, поэтому желтый - красный светодиод)
//
// главная дорога важнее: зеленый на ней горит дольше (15 с), чем на второстепенной (6 с)
// на HEX1 HEX0 - сколько секунд осталось до смены сигнала, KEY0 - сброс

#include "system.h"
#include "altera_avalon_pio_regs.h"
#include "sys/alt_stdio.h"
#include <unistd.h>

// одна фаза работы перекрестка
typedef struct
{
  int ledr;          // какие красные светодиоды горят (красный и желтый сигналы)
  int ledg;          // какие зеленые светодиоды горят
  int seconds;       // длительность фазы, с
  const char *name;  // название фазы для консоли
} phase_t;

// цикл работы перекрестка, 31 секунда
static const phase_t cycle[] =
{
  // главная: зеленый,         второстепенная: красный
  { (1 << 4),                                     (1 << 0) | (1 << 1), 15, "main: green,      side: red\n" },
  // главная: желтый,          второстепенная: красный
  { (1 << 1) | (1 << 3) | (1 << 4),               0,                    3, "main: yellow,     side: red\n" },
  // главная: красный,         второстепенная: красный + желтый
  { (1 << 0) | (1 << 2) | (1 << 4) | (1 << 5),    0,                    2, "main: red,        side: red+yellow\n" },
  // главная: красный,         второстепенная: зеленый
  { (1 << 0) | (1 << 2),                          (1 << 2),             6, "main: red,        side: green\n" },
  // главная: красный,         второстепенная: желтый
  { (1 << 0) | (1 << 2) | (1 << 5),               0,                    3, "main: red,        side: yellow\n" },
  // главная: красный + желтый, второстепенная: красный
  { (1 << 0) | (1 << 1) | (1 << 2) | (1 << 3) | (1 << 4), 0,            2, "main: red+yellow, side: red\n" },
};
#define PHASES (sizeof(cycle) / sizeof(cycle[0]))

int main(void)
{
  unsigned int p;   // номер фазы
  int t;            // сколько секунд осталось

  alt_putstr("Traffic light, variant 3: main road 2 lanes, side road 1 lane\n");

  while (1)
  {
    for (p = 0; p < PHASES; p++)
    {
      alt_putstr(cycle[p].name);                                // название фазы в консоль
      IOWR_ALTERA_AVALON_PIO_DATA(LEDR_BASE, cycle[p].ledr);    // включаем сигналы
      IOWR_ALTERA_AVALON_PIO_DATA(LEDG_BASE, cycle[p].ledg);

      for (t = cycle[p].seconds; t > 0; t--)                    // обратный отсчет
      {
        IOWR_ALTERA_AVALON_PIO_DATA(HEX_BCD_BASE, ((t / 10) << 4) | (t % 10));  // две цифры на HEX1 HEX0
        usleep(1000000);                                        // ждем 1 секунду
      }
    }
  }
  return 0;
}
