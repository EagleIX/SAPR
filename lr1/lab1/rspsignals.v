// rspsignals.v -- распределитель сигналов, вариант 15
// Последовательность Y: 3,2,1,1,2,3,4,4,... (при Q = 7,6,5,4,3,2,1,0)
// Y[3..0] - унитарный (one-hot) код: Y=1 -> 0001, 2 -> 0010, 3 -> 0100, 4 -> 1000
// Y[0] -> LEDG4, Y[1] -> LEDG5, Y[2] -> LEDG6, Y[3] -> LEDG7
module rspsignals
(
	Q, Y
);

input [2:0] Q;
output [3:0] Y;

reg [3:0] Y;

always @(Q)
	case (Q)
		3'b111 : Y = 4'b0100;   // Q=7 -> Y=3
		3'b110 : Y = 4'b0010;   // Q=6 -> Y=2
		3'b101 : Y = 4'b0001;   // Q=5 -> Y=1
		3'b100 : Y = 4'b0001;   // Q=4 -> Y=1
		3'b011 : Y = 4'b0010;   // Q=3 -> Y=2
		3'b010 : Y = 4'b0100;   // Q=2 -> Y=3
		3'b001 : Y = 4'b1000;   // Q=1 -> Y=4
		3'b000 : Y = 4'b1000;   // Q=0 -> Y=4
	endcase

endmodule
