// schetchik.v -- 3-разрядный счётчик обратного хода (7,6,5,...,0,7,...)
// Вариант 15, ЛР №1 САПР. Автор: Орлов Д.В., М3О-410Б-23
// C - синхросигнал (кнопка KEY[1] платы DE1), Q[2..0] - состояние счётчика
module schetchik
(
	C, Q
);

input C;
output [2:0] Q;

reg [2:0] Q = 3'b111;   // начальное состояние при включении: 7

always @(posedge C)
	Q <= Q - 3'b001;      // D2 = Q2^(~Q1&~Q0), D1 = ~(Q1^Q0), D0 = ~Q0

endmodule
